/**
 * Bundle the Client half into the page's module-loader format.
 *
 * The Harness web shell seeds a frozen module table and evaluates a plugin
 * bundle as `window.__ModuleLoader__.load({ id, factory })`; the factory
 * receives `require` for that table and returns the plugin object. esbuild
 * emits CommonJS with `react` and friends external, so every platform import
 * becomes a `require()` call inside the factory, and this script supplies the
 * `module`/`exports` pair the CJS output expects.
 *
 * Output: lib/client.js (the package's `./client` export).
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

/** Package root, resolved from this script. */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Entry point of the Client half. */
const entry = resolve(root, 'src/client/index.ts');

/** Output path the package exports as `./client`. */
const output = resolve(root, 'lib/client.js');

/** Module specifiers the page provides; everything else is inlined. */
const PLATFORM_MODULES = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'];

const result = await build({
  entryPoints: [entry],
  outfile: output,
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: PLATFORM_MODULES,
  legalComments: 'none',
  logLevel: 'warning',
});

const [artifact] = result.outputFiles;
if (artifact === undefined) throw new Error('esbuild produced no output');

/** Indent bundled code one level so the wrapper reads cleanly. */
const body = artifact.text
  .split('\n')
  .map((line) => (line === '' ? line : `    ${line}`))
  .join('\n');

const wrapped = `/* dsh-vim-control — generated by scripts/build-client.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: 'dsh-vim-control',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  },
});
`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, wrapped, 'utf8');
console.log(`built ${output} (${wrapped.length} bytes)`);
